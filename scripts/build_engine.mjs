// Local browser-only adaptation of pinned AGPL upstream rules. No upstream entry point is imported.
import fs from 'node:fs';
import path from 'node:path';
import {build} from 'esbuild';
const root=process.cwd(), vendor=path.join(root,'vendor/novel-downloader');
const upstream=JSON.parse(fs.readFileSync(path.join(vendor,'UPSTREAM.json'),'utf8'));
const source=fs.readFileSync(path.join(vendor,'src/router/download.ts'),'utf8');
const readme=fs.readFileSync(path.join(vendor,'README.md'),'utf8');
const names=new Map();
for (const m of readme.matchAll(/\[([^\]]+)\]\((https?:\/\/[^)]+)\)/g)) {try {names.set(new URL(m[2]).hostname,m[1]);}catch{}}
const denied={alicesw:'Requires rendered frame integration',dizishu:'Evaluates page-supplied JavaScript',uukanshu:'Invokes arbitrary page callback',linovelib:'Requires page scripts, frames and custom font integration'};
const rules=[], skipped=[]; let hosts=[];
const cases=[...source.matchAll(/case\s+"([^"]+)"\s*:/g)];
for(let i=0;i<cases.length;i++) {
 const match=cases[i]; hosts.push(match[1]);
 const body=source.slice(match.index+match[0].length,cases[i+1]?.index??source.length);
 const item=/const\s*\{\s*(\w+)\s*\}\s*=\s*await import\(\s*"(\.\.\/rules\/[^\"]+)"\s*\)/.exec(body);
 if(!item){if(/\b(?:break|throw|return)\b|import\s*\(/.test(body)){skipped.push({hosts,reason:'Unmapped route requires explicit adapter'});hosts=[];}continue;}
 const [_,symbol,rel]=item, module=rel.replace('../','')+'.ts';
 const accepted=/^rules\/(onePage|twoPage|onePageWithMultiIndexPage|biquge)\//.test(module);
 const filename=path.basename(module,'.ts');
 if(!accepted||denied[filename]) {if(accepted)skipped.push({symbol,hosts,reason:denied[filename]});hosts=[];continue;}
 let id=symbol.toLowerCase();
 const existing=rules.find(r=>r.id===id&&r.source===module);
 if(existing){existing.hosts.push(...hosts);hosts=[];continue;}
 if(rules.some(r=>r.id===id))id+='_'+module.split('/')[1].toLowerCase();
 rules.push({id,name:names.get(hosts[0])??({syosetu:'小説家になろう',syosetuorg:'ハーメルン',alphapolis:'アルファポリス',i60ksw:'60 看书',c69shuba:'69 书吧',c101kanshu:'101 看书',fuxiaoshu:'腐小说',common:'笔趣阁通用'}[id])??hosts[0],hosts:[...hosts],book_patterns:[],book_exclude_patterns:id==='i52shuku'?['.*\\/.*_\\d+\\.html']:[],source:module,export:symbol,status:'unverified',mode:'text',license:upstream.license});
 hosts=[];
}
const imports=rules.map((r,i)=>`  ${JSON.stringify(r.id)}: async () => (await import(${JSON.stringify('../vendor/novel-downloader/src/'+r.source)})).${r.export}`).join(',\n');
const manifest={version:1,upstream,rules,excluded:skipped,limitations:['Rules are imported, not verified on every live site.','Only accessible text is supported; font-obfuscated and image chapters require a dedicated OCR adapter.','Only the current book-page host can receive parser requests.']};
fs.writeFileSync('engine/rules-manifest.json',JSON.stringify(manifest,null,2)+'\n');
fs.writeFileSync('engine/generated.ts',`// Generated by scripts/build_engine.mjs.\nexport const manifest = ${JSON.stringify(manifest)};\nexport const loaders = {\n${imports}\n};\n`);
const shims={rules:'base', 'main/Book':'model','main/Chapter':'model',log:'log','lib/http':'http','lib/misc':'misc','lib/attachments':'attachments','main/Attachment':'attachments'};
const plugin={name:'isolated-parser-runtime',setup(b){
 b.onResolve({filter:/.*/},args=>{
  if(args.path==='p-limit')return {path:path.join(root,'engine/shims/limit.ts')};
  if(!args.importer.startsWith(vendor)||!args.path.startsWith('.'))return;
  const abs=path.resolve(path.dirname(args.importer),args.path).replace(/\.ts$/,'');
  const key=path.relative(path.join(vendor,'src'),abs);
  if(shims[key])return {path:path.join(root,`engine/shims/${shims[key]}.ts`)};
 });
}};
const result=await build({entryPoints:['engine/bridge.ts'],bundle:true,outfile:'engine/dist/novelist-rules.js',format:'esm',platform:'browser',target:'chrome110',minify:false,metafile:true,legalComments:'eof',inject:['engine/inject.ts'],plugins:[plugin],banner:{js:`/*! Novel-downloader parser adaptation. AGPL-3.0-or-later. Source: ${upstream.repository} @ ${upstream.commit}. See vendor/novel-downloader/license.txt and engine/NOTICES.md. */`}});
const artifact=fs.readFileSync('engine/dist/novelist-rules.js','utf8');
if(/^export\s/m.test(artifact))throw Error('Unexpected export in private engine bundle');
fs.writeFileSync('engine/dist/novelist-rules.js','(async () => {\n'+artifact+'\n})();\n');
const inputs=Object.keys(result.metafile.inputs);
const forbidden=inputs.filter(p=>/vendor.*\/(index|global|setting|stat|rules)\.ts$|vendor.*\/(ui|save|router)\//.test(p));
if(forbidden.length)throw Error('Forbidden upstream side-effect module reached bundle: '+forbidden.join(', '));
fs.writeFileSync('engine/dist/build-report.json',JSON.stringify({upstream,rules:rules.length,hosts:new Set(rules.flatMap(r=>r.hosts)).size,inputs,bytes:fs.statSync('engine/dist/novelist-rules.js').size},null,2)+'\n');
console.log(`Built ${rules.length} rules / ${new Set(rules.flatMap(r=>r.hosts)).size} exact hosts; ${skipped.length} unsafe-runtime routes excluded.`);
